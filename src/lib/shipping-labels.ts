import { randomBytes } from "node:crypto";

export function createTrackingNumber(orderNumber: string) {
  const suffix = randomBytes(4).toString("hex").toUpperCase();
  return `VEL-${orderNumber.replace(/\W/g, "").slice(-8)}-${suffix}`;
}

export function createShippingLabelId() {
  return `lbl_${randomBytes(10).toString("hex")}`;
}

function escapeHtml(value: string) {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replaceAll('"', "&quot;");
}

export function buildShippingLabelHtml(input: {
  labelId: string;
  orderNumber: string;
  carrier: string;
  trackingNo: string;
  customerName: string;
  phone?: string;
  address: string;
  itemCount: number;
  weightGrams?: number;
  addressLabel?: string;
  serviceLabel?: string;
}) {
  const barcode = input.trackingNo
    .split("")
    .map((character, index) => {
      const width = ((character.charCodeAt(0) + index) % 3) + 1;
      return `<span style="display:block;width:${width}px;height:62px;background:#111"></span>`;
    })
    .join("");

  return `<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <title>Shipping label ${escapeHtml(input.orderNumber)}</title>
  <style>
    @page { size: 4in 6in; margin: 0; }
    body { margin: 0; color: #111; font: 13px Arial, sans-serif; }
    .label { box-sizing: border-box; width: 4in; min-height: 6in; padding: 18px; border: 2px solid #111; }
    .row { display: flex; justify-content: space-between; gap: 16px; }
    .brand { font-size: 22px; font-weight: 800; letter-spacing: .22em; }
    .meta { text-align: right; font-size: 11px; line-height: 1.5; }
    .rule { margin: 16px 0; border-top: 2px solid #111; }
    .label-name { margin-bottom: 6px; font-size: 10px; font-weight: 700; letter-spacing: .15em; text-transform: uppercase; }
    .address { font-size: 17px; font-weight: 700; line-height: 1.45; }
    .barcode { display: flex; height: 62px; align-items: stretch; justify-content: center; gap: 2px; margin: 24px 0 8px; overflow: hidden; }
    .tracking { text-align: center; font-family: monospace; font-size: 14px; letter-spacing: .08em; }
    .footer { margin-top: 20px; font-size: 10px; color: #555; }
  </style>
</head>
<body>
  <main class="label">
    <div class="row">
      <div class="brand">VELORA</div>
      <div class="meta">${escapeHtml(input.carrier)}<br>${escapeHtml(input.orderNumber)}</div>
    </div>
    <div class="rule"></div>
    <div class="label-name">${escapeHtml(input.addressLabel ?? "Ship to")}</div>
    <div class="address">${escapeHtml(input.customerName)}<br>${escapeHtml(input.address)}</div>
    ${input.phone ? `<p>${escapeHtml(input.phone)}</p>` : ""}
    <div class="rule"></div>
    <div class="row">
      <div><div class="label-name">Pieces</div><strong>${input.itemCount}</strong></div>
      <div><div class="label-name">Weight</div><strong>${input.weightGrams ?? 500} g</strong></div>
      <div><div class="label-name">Service</div><strong>${escapeHtml(input.serviceLabel ?? "UAE Standard")}</strong></div>
    </div>
    <div class="barcode">${barcode}</div>
    <div class="tracking">${escapeHtml(input.trackingNo)}</div>
    <div class="footer">Label ${escapeHtml(input.labelId)} · Generated by Velora Admin</div>
  </main>
  <script>window.addEventListener("load", () => window.print())</script>
</body>
</html>`;
}
